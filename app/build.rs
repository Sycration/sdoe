use cxx_qt_build::{CxxQtBuilder, QmlFile, QmlModule};
use std::path::{Path, PathBuf};
use std::process::Command;

fn qmake_query(var: &str) -> String {
    let qmake = std::env::var("QMAKE").unwrap_or_else(|_| "qmake6".into());
    let out = Command::new(&qmake).args(["-query", var]).output().unwrap_or_else(|e| panic!("{qmake}: {e}"));
    String::from_utf8_lossy(&out.stdout).trim().to_string()
}

/// Passes the libraries and object files of a static Qt library's .prl
/// file to the linker.
fn link_prl(prl: &Path) {
    let Ok(text) = std::fs::read_to_string(prl) else { panic!("{} is missing", prl.display()) };
    let line = text.lines().find_map(|l| l.strip_prefix("QMAKE_PRL_LIBS = ")).unwrap_or("");
    let expanded = line
        .replace("$$[QT_INSTALL_LIBS]", &qmake_query("QT_INSTALL_LIBS"))
        .replace("$$[QT_INSTALL_PLUGINS]", &qmake_query("QT_INSTALL_PLUGINS"))
        .replace("$$[QT_INSTALL_QML]", &qmake_query("QT_INSTALL_QML"))
        .replace("$$[QT_INSTALL_PREFIX]", &qmake_query("QT_INSTALL_PREFIX"));
    for item in expanded.split_whitespace() {
        println!("cargo:rustc-link-arg-bins={item}");
    }
}

/// WebAssembly (Qt for WebAssembly, static and single-threaded): imports the
/// static platform and QML plugins that the QML files use, links them, and
/// sets the emscripten options of Qt's own build. Returns the generated C++
/// file with the plugin imports.
fn webassembly(qml_files: &[&str]) -> PathBuf {
    let qml_dir = qmake_query("QT_INSTALL_QML");
    let scanner = Path::new(&qmake_query("QT_HOST_LIBEXECS")).join("qmlimportscanner");
    let mut cmd = Command::new(&scanner);
    cmd.arg("-qmlFiles").args(qml_files).args(["-importPath", &qml_dir]);
    let out = cmd.output().unwrap_or_else(|e| panic!("{}: {e}", scanner.display()));
    assert!(out.status.success(), "qmlimportscanner failed: {}", String::from_utf8_lossy(&out.stderr));
    let imports: Vec<serde_json::Value> = serde_json::from_slice(&out.stdout).expect("qmlimportscanner output");

    let plugins = PathBuf::from(qmake_query("QT_INSTALL_PLUGINS"));
    let mut cpp = String::from(
        "// Generated by build.rs: static Qt plugins of the WebAssembly build.\n#include <QtPlugin>\n\nQ_IMPORT_PLUGIN(QWasmIntegrationPlugin)\n",
    );
    link_prl(&plugins.join("platforms/libqwasm.prl"));
    let mut seen = std::collections::BTreeSet::new();
    for i in &imports {
        let (Some(class), Some(plugin), Some(path)) = (i["classname"].as_str(), i["plugin"].as_str(), i["path"].as_str()) else {
            continue;
        };
        if !seen.insert(class.to_string()) {
            continue;
        }
        cpp += &format!("Q_IMPORT_PLUGIN({class})\n");
        println!("cargo:rustc-link-arg-bins={path}/lib{plugin}.a");
        link_prl(&Path::new(path).join(format!("lib{plugin}.prl")));
    }
    // cxx-qt registers its types and QML modules from static initializers in
    // libraries that it links with +whole-archive, which rustc does not pass
    // on to emcc; the calls here keep them. The functions run only once.
    let inits = ["crate_cxx_qt", "crate_cxx_qt_lib", "crate_cxx_qt_lib_extras", "crate_sdoe_app", "qml_module_Sdoe"];
    for i in inits {
        cpp += &format!("extern \"C\" bool cxx_qt_init_{i}();\n");
    }
    // Called from main, which keeps this object file and its plugin
    // registrations in the link.
    cpp += "\nextern \"C\" void sdoe_import_static_plugins()\n{\n";
    for i in inits {
        cpp += &format!("    cxx_qt_init_{i}();\n");
    }
    cpp += "}\n";
    let file = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("static_plugins.cpp");
    std::fs::write(&file, cpp).unwrap();

    // Exceptions and setjmp/longjmp: the prebuilt Qt for WebAssembly uses
    // emscripten's JavaScript-based handling, and Rust links with wasm
    // exceptions (-fwasm-exceptions), which emcc cannot combine. The later
    // -fno-exceptions selects the JavaScript-based mode for the link; Rust
    // code panics with abort (the release build sets panic=abort). The
    // precompiled Rust standard library still contains wasm exception
    // landing pads, which need the exception tag that wasm/exception-tag.s
    // defines, and js-eh.js supplies two functions of the JavaScript mode.
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let tag = manifest.join("wasm/exception-tag.s");
    println!("cargo:rerun-if-changed={}", tag.display());
    let tag_obj = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("exception-tag.o");
    let status = Command::new("emcc").arg("-c").arg(&tag).arg("-o").arg(&tag_obj).status().expect("emcc");
    assert!(status.success(), "emcc could not assemble {}", tag.display());
    println!("cargo:rustc-link-arg-bins={}", tag_obj.display());
    println!("cargo:rustc-link-arg-bins=-fno-exceptions");
    // emcc's default without -fwasm-exceptions: throwing allowed (Qt's event
    // loop refers to libc++abi functions of that variant), catching off.
    println!("cargo:rustc-link-arg-bins=-sDISABLE_EXCEPTION_THROWING=0");
    // rustc exports every exported Rust function, and emcc rejects names
    // with '$' (from cxx); JavaScript needs only main.
    println!("cargo:rustc-link-arg-bins=-sEXPORTED_FUNCTIONS=_main");

    // The settings of Qt's CMake build for WebAssembly applications.
    for arg in [
        "-sMAX_WEBGL_VERSION=2",
        "-sWASM_BIGINT=1",
        "-sSTACK_SIZE=5MB",
        "-sFETCH",
        "-sALLOW_MEMORY_GROWTH",
        "-sERROR_ON_UNDEFINED_SYMBOLS=1",
        "-sINITIAL_MEMORY=50MB",
        "-sMAXIMUM_MEMORY=4GB",
        "-sEXPORTED_RUNTIME_METHODS=UTF16ToString,stringToUTF16,JSEvents,specialHTMLTargets,FS,callMain",
        "-sMODULARIZE=1",
        "-sEXPORT_NAME=sdoe_entry",
        "-lembind",
    ] {
        println!("cargo:rustc-link-arg-bins={arg}");
    }
    let js_eh = manifest.join("wasm/js-eh.js");
    println!("cargo:rerun-if-changed={}", js_eh.display());
    println!("cargo:rustc-link-arg-bins=--js-library={}", js_eh.display());
    file
}

fn main() {
    let qml = [
        "qml/Main.qml",
        "qml/Theme.qml",
        "qml/Api.qml",
        "qml/SheetView.qml",
        "qml/ResultTable.qml",
        "qml/PlotView.qml",
        "qml/OptionsForm.qml",
        "qml/SetupPage.qml",
        "qml/DesignPage.qml",
        "qml/RunsPage.qml",
        "qml/AnalysisPage.qml",
        "qml/OptimizePage.qml",
        "qml/EvaluatePage.qml",
        "qml/ImportDialog.qml",
        "qml/NextRunDialog.qml",
        "qml/FactorValueEditor.qml",
        "qml/Section.qml",
        "qml/FitMenu.qml",
        "qml/FitComboBox.qml",
        "qml/HelpWindow.qml",
    ];
    for f in qml {
        println!("cargo:rerun-if-changed={f}");
    }
    // cxx-qt-build reads this (the release script selects zlib) without
    // declaring it.
    println!("cargo:rerun-if-env-changed=CXX_QT_AUTORCC_OPTIONS");
    let files: Vec<QmlFile> = qml
        .iter()
        .map(|f| QmlFile::from(f).singleton(f.ends_with("Theme.qml") || f.ends_with("Api.qml")))
        .collect();
    let mut builder = CxxQtBuilder::new_qml_module(QmlModule::new("Sdoe").qml_files(files));
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("emscripten") {
        println!("cargo:rerun-if-env-changed=QMAKE");
        builder = builder.cpp_file(webassembly(&qml));
    }
    builder
        .qt_module("Quick")
        .qt_module("QuickControls2")
        .qt_module("Widgets")
        .files(["src/bridge.rs"])
        .cpp_file("cpp/webfile.cpp")
        .build();
}
